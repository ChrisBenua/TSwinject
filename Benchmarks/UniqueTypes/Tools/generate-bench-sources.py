#!/usr/bin/env python3
"""Generates the unique-types benchmark sources.

Writes three things:

  Sources/BenchModels/Generated/Protocols/   N public protocols, `per_file` per file
  Sources/BenchModels/Generated/Classes/     N public final classes, one per protocol
  Sources/Bench{TSwinject,Swinject}/Generated/{Registration,Resolution}.swift

The two runner copies of Registration/Resolution differ in exactly one line —
`import TSwinject` vs. `import Swinject`. Both containers accept
`container.register(P.self) { _ in C() }` and `container.resolve(P.self)`
unchanged; the import is needed only because some of those methods live in
extensions, which are visible only to files that import the defining module.

Re-running with the same arguments reproduces the committed tree exactly.

    python3 Tools/generate-bench-sources.py                  # 10 000 types
    python3 Tools/generate-bench-sources.py --types 50000
"""

import argparse
import os
import shutil

HEADER = """// AUTO-GENERATED — do not edit by hand.
// Generated by Tools/generate-bench-sources.py

import Foundation
"""


def protocol_file(start, count):
    out = [HEADER]
    for i in range(start, start + count):
        out.append(
            f"""
public protocol Protocol{i} {{
    func identifier() -> String
}}
"""
        )
    return "".join(out)


def class_file(start, count):
    out = [HEADER]
    for i in range(start, start + count):
        out.append(
            f"""
public final class Class{i}: Protocol{i}, Codable {{
    public let id: Int
    public let name: String
    public let value: Double
    public let isActive: Bool
    public let createdAt: Date

    public init(
        id: Int = {i},
        name: String = "Class{i}",
        value: Double = {i}.0,
        isActive: Bool = true,
        createdAt: Date = Date()
    ) {{
        self.id        = id
        self.name      = name
        self.value     = value
        self.isActive  = isActive
        self.createdAt = createdAt
    }}

    // MARK: Protocol{i}
    public func identifier() -> String {{ "Class{i}(\\(id))" }}
}}
"""
        )
    return "".join(out)


def registration_file(types, chunk, di_module):
    chunks = list(range(0, types, chunk))
    out = [
        HEADER,
        f"\nimport BenchModels\nimport {di_module}\n",
        "\n/// How many protocol/class pairs this benchmark was generated with.\n",
        f"public let benchTypeCount = {types}\n",
        "\n// MARK: - Public entry point\n\n",
        "/// Registers every generated type under its own protocol, in the container's\n",
        "/// default object scope.\n",
        "public func registerAll(in container: Container) {\n",
    ]
    for n, _ in enumerate(chunks):
        out.append(f"    _register_{n:04d}(in: container)\n")
    out.append("}\n")

    # One 10 000-line function does not type-check in reasonable time; chunking is
    # what keeps the build minutes rather than hours.
    for n, start in enumerate(chunks):
        out.append(f"\n// MARK: chunk {n}\nprivate func _register_{n:04d}(in container: Container) {{\n")
        for i in range(start, min(start + chunk, types)):
            out.append(f"    container.register(Protocol{i}.self) {{ _ in Class{i}() }}\n")
        out.append("}\n")
    return "".join(out)


def resolution_file(types, chunk, di_module):
    chunks = list(range(0, types, chunk))
    out = [
        HEADER,
        f"\nimport BenchModels\nimport {di_module}\n",
        "\n// MARK: - Public entry point\n\n",
        "/// Resolves every registered protocol once, returning the instances so the\n",
        "/// optimiser cannot discard the work.\n",
        "@discardableResult\npublic func resolveAll(from container: Container) -> [Any] {\n",
        "    var result: [Any] = []\n",
        f"    result.reserveCapacity({types})\n",
    ]
    for n, _ in enumerate(chunks):
        out.append(f"    result += _resolve_{n:04d}(from: container)\n")
    out.append("    return result\n}\n")

    for n, start in enumerate(chunks):
        size = min(start + chunk, types) - start
        out.append(f"\n// MARK: chunk {n}\nprivate func _resolve_{n:04d}(from container: Container) -> [Any] {{\n")
        out.append("    var out: [Any] = []\n")
        out.append(f"    out.reserveCapacity({size})\n")
        for i in range(start, start + size):
            out.append(f"    if let v = container.resolve(Protocol{i}.self) {{ out.append(v) }}\n")
        out.append("    return out\n}\n")
    return "".join(out)


def rewrite_dir(path, files):
    """Replaces `path` wholesale so a smaller --types leaves no stale files behind."""
    if os.path.isdir(path):
        shutil.rmtree(path)
    os.makedirs(path)
    for name, body in files:
        with open(os.path.join(path, name), "w", encoding="utf-8") as handle:
            handle.write(body)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--types", type=int, default=10000, help="number of protocol/class pairs")
    parser.add_argument("--per-file", type=int, default=10, help="declarations per generated model file")
    parser.add_argument("--chunk", type=int, default=500, help="registrations/resolutions per function")
    parser.add_argument(
        "--out",
        default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        help="benchmark package root (default: the package this script lives in)",
    )
    args = parser.parse_args()

    models = os.path.join(args.out, "Sources", "BenchModels", "Generated")
    starts = list(range(0, args.types, args.per_file))

    rewrite_dir(
        os.path.join(models, "Protocols"),
        [
            (f"Protocols_{n:04d}.swift", protocol_file(start, min(args.per_file, args.types - start)))
            for n, start in enumerate(starts)
        ],
    )
    rewrite_dir(
        os.path.join(models, "Classes"),
        [
            (f"Classes_{n:04d}.swift", class_file(start, min(args.per_file, args.types - start)))
            for n, start in enumerate(starts)
        ],
    )

    for runner, di_module in (("BenchTSwinject", "TSwinject"), ("BenchSwinject", "Swinject")):
        rewrite_dir(
            os.path.join(args.out, "Sources", runner, "Generated"),
            [
                ("Registration.swift", registration_file(args.types, args.chunk, di_module)),
                ("Resolution.swift", resolution_file(args.types, args.chunk, di_module)),
            ],
        )

    print(
        f"generated {args.types} protocol/class pairs "
        f"({len(starts)} model files each), {len(range(0, args.types, args.chunk))} DI chunks"
    )


if __name__ == "__main__":
    main()
